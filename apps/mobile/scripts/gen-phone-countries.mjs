// Rebuild the offline phone-country catalog without downloading anything:
//   node apps/mobile/scripts/gen-phone-countries.mjs [--check]
//
// Calling codes come from the exact libphonenumber-js version installed by the
// mobile lockfile (MIT). Localized names come from Unicode CLDR 49.0.0
// (Unicode-3.0); the original files and license are in data/phone-countries/.
// Pinned upstream source:
// https://github.com/unicode-org/cldr-json/tree/49.0.0/cldr-json/cldr-localenames-full/main
//
// The catalog deliberately follows libphonenumber's geographic dialing regions,
// including AC, TA, and XK. ISO regions without a supported telephone numbering
// plan are not assigned invented calling codes. Non-geographic services such as
// +800 are phone numbers, but are not countries in the picker.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { getCountries, getCountryCallingCode } from "libphonenumber-js";

const expectedPhoneVersion = "1.13.15";
const phonePackage = JSON.parse(
  readFileSync(new URL("../node_modules/libphonenumber-js/package.json", import.meta.url), "utf8"),
);
if (phonePackage.version !== expectedPhoneVersion) {
  throw new Error(`Review country metadata before updating libphonenumber-js ${phonePackage.version}`);
}

const sourceHashes = {
  en: "1326fb3bcdf8b8cf63df73ea02ea7f8bf7a8362cbb60bd12bcdb53f3ad22bf04",
  "fa-AF": "3934dc2de86ff6f3cbe94d8e21d99db3fdb15494a75ca648e59648b78c99b500",
  ps: "1658c008691ef3c8fa44968beba39648cc977314c2d77b0c3ee70a297a5fb8d7",
};
const names = Object.fromEntries(
  Object.entries(sourceHashes).map(([locale, expectedHash]) => {
    // Git may use CRLF on Windows. Hash canonical LF so a clean checkout of
    // these exact upstream JSON files produces the same result on every OS.
    const source = readFileSync(
      new URL(`./data/phone-countries/${locale}.json`, import.meta.url),
      "utf8",
    ).replace(/\r\n/g, "\n");
    if (createHash("sha256").update(source).digest("hex") !== expectedHash) {
      throw new Error(`The pinned CLDR ${locale} source has changed`);
    }
    return [locale, JSON.parse(source).main[locale].localeDisplayNames.territories];
  }),
);

// Keep labels already reviewed for Kaata's Afghan market. Every other country
// uses the complete CLDR translation, rather than an English-name fallback.
const labelOverrides = {
  AU: { nameFa: "آسترالیا", namePs: "اسټرالیا" },
  DE: { namePs: "جرمني" },
  NL: { nameFa: "هالند", namePs: "هالنډ" },
  SE: { nameFa: "سویدن", namePs: "سویډن" },
  TR: { name: "Turkey", namePs: "ترکیه" },
  AE: { name: "UAE", nameFa: "امارات متحده عربی", namePs: "متحده عربي امارات" },
  GB: { nameFa: "بریتانیا", namePs: "بریتانیا" },
  US: { nameFa: "ایالات متحده امریکا", namePs: "د امریکا متحده ایالات" },
};

const countries = getCountries().map((code) => {
  const labels = { name: names.en[code], nameFa: names["fa-AF"][code], namePs: names.ps[code] };
  if (Object.values(labels).some((name) => typeof name !== "string" || !name)) {
    throw new Error(`Missing CLDR country name for ${code}`);
  }
  return {
    code,
    ...labels,
    ...labelOverrides[code],
    dialCode: `+${getCountryCallingCode(code)}`,
    flag: String.fromCodePoint(...[...code].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65)),
  };
});
// Stable code-point ordering makes output independent of the host ICU version.
countries.sort((a, b) => {
  if (a.code === "AF") return -1;
  if (b.code === "AF") return 1;
  return a.name < b.name ? -1 : a.name > b.name ? 1 : 0;
});

const output = `// Generated by scripts/gen-phone-countries.mjs. Do not edit by hand.
// 245 geographic dialing regions: libphonenumber-js 1.13.15 (MIT).
// Names: Unicode CLDR 49.0.0, en / fa-AF / ps (Unicode-3.0).
// Full Unicode notice: scripts/data/phone-countries/LICENSE.
// Afghanistan stays first; the rest are ordered by English display name.
// Shared calling codes are intentional: e.g. US/CA +1, GB/JE +44, IT/VA +39.
export type Country = {
  code: string;
  name: string;
  nameFa: string;
  namePs: string;
  dialCode: string;
  flag: string;
};

export const COUNTRIES: Country[] = ${JSON.stringify(countries, null, 2)};
`;
const target = new URL("../lib/phone-countries.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) {
    throw new Error("phone-countries.ts is out of date");
  }
  console.log(`Verified ${countries.length} phone countries and all three localized names`);
} else {
  writeFileSync(target, output);
  console.log(`Generated ${countries.length} phone countries in ${fileURLToPath(target)}`);
}
