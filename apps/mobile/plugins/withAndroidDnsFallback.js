const { withDangerousMod, withMainApplication } = require("@expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const MARKER = "// Generated by plugins/withAndroidDnsFallback.js";
const INSTALL = "af.kaata.app.network.KaataDnsFallback.install(this)";

module.exports = function withAndroidDnsFallback(config) {
  if (config.android?.package !== "af.kaata.app") {
    throw new Error("Review Kaata's DNS integration before changing the Android package.");
  }
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const target = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "java",
        "af",
        "kaata",
        "app",
        "network",
        "KaataDnsFallback.kt",
      );
      if (fs.existsSync(target) && !fs.readFileSync(target, "utf8").startsWith(MARKER)) {
        throw new Error("Refusing to replace an unrecognized Kaata DNS integration.");
      }
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(path.join(__dirname, "android", "KaataDnsFallback.kt"), target);
      return cfg;
    },
  ]);
  return withMainApplication(config, (cfg) => {
    if (cfg.modResults.language !== "kt") {
      throw new Error("Kaata DNS recovery requires the reviewed Kotlin MainApplication template.");
    }
    let contents = cfg.modResults.contents;
    if (contents.includes("setOkHttpClientFactory")) {
      throw new Error(
        "An existing Android HTTP factory needs an explicit merge with Kaata DNS recovery.",
      );
    }
    const startup = /^([ \t]*)loadReactNative\(this\)[ \t]*(\r?)$/gm;
    if ([...contents.matchAll(startup)].length !== 1) {
      throw new Error(
        "Could not identify the single React Native startup call for Kaata DNS recovery.",
      );
    }
    if (contents.includes(INSTALL)) {
      const expected = new RegExp(
        `${MARKER.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\r?\\n[ \\t]*af\\.kaata\\.app\\.network\\.KaataDnsFallback\\.install\\(this\\)\\r?\\n[ \\t]*loadReactNative\\(this\\)`,
      );
      if (!expected.test(contents) || contents.split(INSTALL).length !== 2) {
        throw new Error(
          "Kaata DNS recovery must be installed once immediately before React Native starts.",
        );
      }
    } else {
      if (contents.includes("KaataDnsFallback")) {
        throw new Error(
          "An existing Android HTTP factory needs an explicit merge with Kaata DNS recovery.",
        );
      }
      contents = contents.replace(
        startup,
        (_, indent, carriageReturn) =>
          `${indent}${MARKER}${carriageReturn}\n${indent}${INSTALL}${carriageReturn}\n${indent}loadReactNative(this)${carriageReturn}`,
      );
    }
    cfg.modResults.contents = contents;
    return cfg;
  });
};
