// Android 7.0 predates ISRG Root X1. Add that public root only for Kaata,
// retaining Android's certificate/path/hostname checks and normal system roots.
// Android 8+ selects xml-v26 and uses only its system trust store, including its
// normal certificate-transparency policy on newer Android versions.
const { withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");
const { X509Certificate } = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const RESOURCE = "kaata_network_security_config";
const ROOT_RESOURCE = "kaata_isrg_root_x1";
const GENERATED = "Generated by plugins/withLegacyAndroidTls.js";
const ROOT_FINGERPRINT =
  "96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:CF:E8:A3:C0:AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6";

function checkedRoot() {
  const pem = fs.readFileSync(path.join(__dirname, "certificates", "isrg_root_x1.pem"));
  const certificate = new X509Certificate(pem);
  if (
    certificate.fingerprint256 !== ROOT_FINGERPRINT ||
    !certificate.ca ||
    !certificate.checkIssued(certificate) ||
    !certificate.verify(certificate.publicKey)
  ) {
    throw new Error("Kaata's Android compatibility root does not match the reviewed public CA.");
  }
  // Copy only the verified certificate, never an unchecked second PEM block
  // or other bytes accidentally appended to the reviewed asset.
  return Buffer.from(certificate.toString());
}

function networkConfig(legacy, allowCleartext) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED}. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="${allowCleartext}">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="false">
        <domain includeSubdomains="true">kaata.af</domain>${
          legacy
            ? `
        <trust-anchors>
            <certificates src="system" />
            <certificates src="@raw/${ROOT_RESOURCE}" />
        </trust-anchors>`
            : ""
        }
    </domain-config>
</network-security-config>
`;
}

module.exports = function withLegacyAndroidTls(config) {
  // Once Network Security Config is present, Android ignores the manifest's
  // usesCleartextTraffic flag. Preserve the existing build-properties choice
  // for local development servers; Kaata's public domains always require TLS.
  const buildProperties = (config.plugins ?? []).find(
    (plugin) => Array.isArray(plugin) && plugin[0] === "expo-build-properties",
  );
  const allowCleartext = buildProperties?.[1]?.android?.usesCleartextTraffic ?? false;
  if (typeof allowCleartext !== "boolean") {
    throw new Error("expo-build-properties android.usesCleartextTraffic must be a boolean.");
  }

  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const root = checkedRoot();
      const res = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res");
      const files = [
        [path.join(res, "xml", `${RESOURCE}.xml`), networkConfig(true, allowCleartext)],
        [path.join(res, "xml-v26", `${RESOURCE}.xml`), networkConfig(false, allowCleartext)],
        [path.join(res, "raw", `${ROOT_RESOURCE}.pem`), root],
      ];
      // Check every target before writing, so a pre-existing configuration is
      // never silently replaced with a different security policy.
      for (const [file, content] of files) {
        if (!fs.existsSync(file)) continue;
        const current = fs.readFileSync(file);
        if (Buffer.isBuffer(content)) {
          if (new X509Certificate(current).fingerprint256 !== ROOT_FINGERPRINT) {
            throw new Error(`Refusing to replace an unrecognized TLS root: ${file}`);
          }
        } else if (!current.toString("utf8").includes(GENERATED)) {
          throw new Error(
            `Refusing to replace an existing network security configuration: ${file}`,
          );
        }
      }
      for (const [file, content] of files) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
      }
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults?.manifest?.application?.[0];
    if (!app?.$) throw new Error("Android application manifest is missing.");
    const existing = app.$["android:networkSecurityConfig"];
    if (existing && existing !== `@xml/${RESOURCE}`) {
      throw new Error(
        "Kaata already has another Android network security configuration; merge it explicitly.",
      );
    }
    const manifestCleartext = app.$["android:usesCleartextTraffic"];
    if (manifestCleartext != null && String(manifestCleartext) !== String(allowCleartext)) {
      throw new Error(
        "Android cleartext policy differs from expo-build-properties; reconcile it before building.",
      );
    }
    app.$["android:networkSecurityConfig"] = `@xml/${RESOURCE}`;
    return cfg;
  });
};
