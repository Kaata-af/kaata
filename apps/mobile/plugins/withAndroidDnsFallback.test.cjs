const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { test } = require("node:test");
const plugin = require("./withAndroidDnsFallback");

const template = `package af.kaata.app
class MainApplication : Application(), ReactApplication {
  override fun onCreate() {
    super.onCreate()
    loadReactNative(this)
    ApplicationLifecycleDispatcher.onApplicationCreate(this)
  }
}
`;
const install = "af.kaata.app.network.KaataDnsFallback.install(this)";
const marker = "// Generated by plugins/withAndroidDnsFallback.js";

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "kaata-dns-plugin-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const config = plugin({ name: "Kaata", slug: "kaata", android: { package: "af.kaata.app" } });
  const modRequest = { projectRoot: root, platformProjectRoot: path.join(root, "android") };
  const source = path.join(
    modRequest.platformProjectRoot,
    "app",
    "src",
    "main",
    "java",
    "af",
    "kaata",
    "app",
    "network",
    "KaataDnsFallback.kt",
  );
  return {
    source,
    generate: () => config.mods.android.dangerous({ ...config, modRequest, modResults: {} }),
    apply: (contents = template, language = "kt") =>
      config.mods.android.mainApplication({
        ...config,
        modRequest,
        modResults: { contents, language, path: "MainApplication.kt" },
      }),
  };
}

test("installs once before React Native and preserves application lifecycle", async (t) => {
  const f = fixture(t);
  const first = (await f.apply()).modResults.contents;
  assert.ok(first.indexOf(install) > first.indexOf("super.onCreate()"));
  assert.ok(first.indexOf(install) < first.indexOf("loadReactNative(this)"));
  assert.equal(first.replace(`    ${marker}\n    ${install}\n`, ""), template);
  assert.equal((await f.apply(first)).modResults.contents, first);
});

test("generated source matches the reviewed source exactly and can be regenerated", async (t) => {
  const f = fixture(t);
  await f.generate();
  const original = fs.readFileSync(path.join(__dirname, "android", "KaataDnsFallback.kt"), "utf8");
  assert.equal(fs.readFileSync(f.source, "utf8"), original);
  await f.generate();
  assert.equal(fs.readFileSync(f.source, "utf8"), original);
});

test("preserves Windows line endings and remains idempotent", async (t) => {
  const f = fixture(t);
  const windows = template.replaceAll("\n", "\r\n");
  const first = (await f.apply(windows)).modResults.contents;
  assert.equal(first.replace(`    ${marker}\r\n    ${install}\r\n`, ""), windows);
  assert.doesNotMatch(first, /(?<!\r)\n/);
  assert.equal((await f.apply(first)).modResults.contents, first);
});

test("unfamiliar templates, reordered installs and duplicate startup calls fail closed", async (t) => {
  const f = fixture(t);
  await assert.rejects(f.apply(template, "java"), /Kotlin/);
  await assert.rejects(
    f.apply(template.replace("loadReactNative(this)", "startReactNative(this)")),
    /single React Native startup/,
  );
  await assert.rejects(
    f.apply(
      template.replace("loadReactNative(this)", "loadReactNative(this)\n    loadReactNative(this)"),
    ),
    /single React Native startup/,
  );
  await assert.rejects(
    f.apply(template.replace("super.onCreate()", `super.onCreate()\n    ${install}`)),
    /once immediately before/,
  );
  const first = (await f.apply()).modResults.contents;
  await assert.rejects(
    f.apply(first.replace("super.onCreate()", `super.onCreate()\n    ${install}`)),
    /once immediately before/,
  );
});

test("another networking factory or source file requires explicit integration", async (t) => {
  const f = fixture(t);
  await assert.rejects(
    f.apply(
      template.replace(
        "super.onCreate()",
        "super.onCreate()\n    OkHttpClientProvider.setOkHttpClientFactory(otherFactory)",
      ),
    ),
    /explicit merge/,
  );
  const installed = (await f.apply()).modResults.contents;
  await assert.rejects(
    f.apply(installed + "\nfun other() = setOkHttpClientFactory(other)"),
    /explicit merge/,
  );
  fs.mkdirSync(path.dirname(f.source), { recursive: true });
  fs.writeFileSync(f.source, "package custom\nclass KaataDnsFallback");
  await assert.rejects(f.generate(), /unrecognized/);
  assert.equal(fs.readFileSync(f.source, "utf8"), "package custom\nclass KaataDnsFallback");
});

test("changed application identity requires a deliberate review", () => {
  assert.throws(
    () => plugin({ android: { package: "other.app" } }),
    /changing the Android package/,
  );
});

test("app registers DNS recovery alongside the scoped Android 7 TLS compatibility plugin", () => {
  const config = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "app.json"))).expo;
  assert.equal(config.plugins.filter((x) => x === "./plugins/withAndroidDnsFallback").length, 1);
  assert.ok(config.plugins.includes("./plugins/withLegacyAndroidTls"));
  assert.ok(config.android.permissions.includes("android.permission.ACCESS_NETWORK_STATE"));
});
