const copy = { en, fa, ps };

export function customRoleText(key: Key, vars?: Record<string, string | number>): string {
  const message = copy[getLocale()][key];
  return vars ? message.replace(/\{(\w+)\}/g, (part, name) => String(vars[name] ?? part)) : message;
}

export function customRolePresetName(preset: CustomRolePreset): string {
  return t(`vaultSettings.role.${preset}`);
}
