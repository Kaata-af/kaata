export function pdfCopy(locale: LocaleCode, key: Key, values: Record<string, string> = {}): string {
  return (locale === "fa" ? fa : locale === "ps" ? ps : en)[key].replace(
    /\{(\w+)\}/g,
    (placeholder, name: string) => values[name] ?? placeholder,
  );
}
